HEADER = "/* Generated by frontend/tools/generate_themes.py. Edit the script, not this file. */\n"


def slug(name):
    return re.sub(r"[^A-Za-z0-9]", "", name)


def hls(hex_color):
    r, g, b = (int(hex_color[i : i + 2], 16) / 255 for i in (1, 3, 5))
    return colorsys.rgb_to_hls(r, g, b)


def with_lightness(hex_color, lightness, min_saturation=0.0):
    h, _, s = hls(hex_color)
    lightness = min(max(lightness, 0.0), 1.0)
    r, g, b = colorsys.hls_to_rgb(h, lightness, max(s, min_saturation) if s > 0.02 else s)
    return "rgb({},{},{})".format(round(r * 255), round(g * 255), round(b * 255))


def greys(base, offsets):
    _, lightness, _ = hls(base)
    return {"--grey{}".format(i + 1): with_lightness(base, lightness + off / 100) for i, off in enumerate(offsets)}


# Lightness of grey1..grey8 relative to bg_base (grey6), as in Yami and Yami_Light
DARK_GREY_OFFSETS = [22, 17, 13, 9, 4, 0, -5, -9]
LIGHT_GREY_OFFSETS = [-35, 9.6, 9.6, 6, 2.5, 0, -7, -14]


def dark_accent(accent):
    return {
        "--primary": with_lightness(accent, 0.44, 0.45),
        "--primary_light": with_lightness(accent, 0.56, 0.45),
        "--primary_lighter": with_lightness(accent, 0.66, 0.45),
        "--primary_dark": with_lightness(accent, 0.36, 0.45),
        "--primary_darker": with_lightness(accent, 0.29, 0.45),
    }


def light_accent(accent):
    return {
        "--primary": with_lightness(accent, 0.77, 0.45),
        "--primary_light": with_lightness(accent, 0.85, 0.45),
        "--primary_lighter": with_lightness(accent, 0.62, 0.45),
        "--primary_dark": with_lightness(accent, 0.72, 0.45),
        "--primary_darker": with_lightness(accent, 0.65, 0.45),
    }


def meta(name, theme_id, extends, dark):
    return (
        "@OBSThemeMeta {{\n"
        "    name: '{}';\n"
        "    id: '{}';\n"
        "    extends: '{}';\n"
        "    author: 'Generated';\n"
        "    dark: '{}';\n"
        "}}\n".format(name, theme_id, extends, "true" if dark else "false")
    )


def vars_block(values):
    lines = ["    {}: {};".format(k, v) for k, v in values.items()]
    return "@OBSThemeVars {\n" + "\n".join(lines) + "\n}\n"


def light_rules():
    """Yami_Light's variables and rules, which every light theme needs"""
    text = (THEMES_DIR / "Yami_Light.ovt").read_text()
    vars_match = re.search(r"@OBSThemeVars \{(.*?)\n\}\n", text, re.S)
    light_vars = dict(re.findall(r"(--[\w-]+):\s*([^;]+);", vars_match.group(1)))
    return light_vars, text[vars_match.end() :]


def theme_id(name):
    return "com.obsproject.Themes." + slug(name)


def write(path, content):
    path.write_text(content)


def main():
    STYLES_DIR.mkdir(exist_ok=True)
    for old in list(THEMES_DIR.glob("Theme_*")) + list(STYLES_DIR.glob("*.ovt")):
        old.unlink()

    light_vars, light_body = light_rules()

    for name, base, accent in DARK_THEMES + LIGHT_THEMES:
        dark = (name, base, accent) in DARK_THEMES
        values = {}
        if dark:
            values.update(greys(base, DARK_GREY_OFFSETS))
            values.update(dark_accent(accent))
            body = ""
        else:
            values.update(light_vars)
            values.update(greys(base, LIGHT_GREY_OFFSETS))
            values.update(light_accent(accent))
            body = light_body
        tid = theme_id(name)
        write(
            THEMES_DIR / "Theme_{}.obt".format(slug(name)),
            HEADER + "\n" + meta(name, tid, "com.obsproject.Yami", dark) + "\n" + vars_block(values) + body,
        )
        write(
            THEMES_DIR / "Theme_{}_Default.ovt".format(slug(name)),
            HEADER + "\n" + meta("Default", tid + ".Default", tid, dark),
        )

    for name, accent in STYLES:
        sid = "com.obsproject.Styles." + slug(name)
        write(
            STYLES_DIR / "{}.ovt".format(slug(name)),
            HEADER + "\n" + meta(name, sid, "com.obsproject.Yami", True) + "\n" + vars_block(dark_accent(accent)),
        )
        write(
            STYLES_DIR / "{}.light.ovt".format(slug(name)),
            HEADER + "\n" + meta(name, sid, "com.obsproject.Yami", False) + "\n" + vars_block(light_accent(accent)),
        )

    print("{} themes, {} styles".format(len(DARK_THEMES) + len(LIGHT_THEMES) + 1, len(STYLES)))


if __name__ == "__main__":
    main()
